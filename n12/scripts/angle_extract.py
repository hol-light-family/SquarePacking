#!/usr/bin/env python3
"""Extract the S12 angle enclosures (source/S12/AngleData64.lean, AngleData128.lean)
and emit the HOL Light data files n12/certlib/AngleData64.ml / AngleData128.ml.

Usage: python3 n12/scripts/angle_extract.py [64|128|all]
Each Lean line  def angle64_k : AngleEnclosure := <l,u,c,s,outer,inner,wall>
becomes the HOL term  AngleEnc l u c s outer inner wall  with rationals p/q
written as (&p / &q).  The emitted file defines the list angles64 (resp.
angles128) in Lean's order, proves ae_check of every element with
AE_CHECK_RULE (kernel-checked rational arithmetic), the indexed theorem
!k. k < 64 ==> ae_check (EL k angles64), and Lean's angles64_cover.
"""
import re, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "n12/ext/jatloe/Lean/Proofs/N12-jatloe/source/S12")
OUT = os.path.join(ROOT, "n12/certlib")

def hol_rat(tok):
    tok = tok.strip()
    if tok.startswith("(") and tok.endswith(")"):
        tok = tok[1:-1].strip()
    neg = tok.startswith("-")
    if neg:
        tok = tok[1:].strip()
    m = re.fullmatch(r"(\d+)\s*/\s*(\d+)", tok)
    if m:
        s = "(&%s / &%s)" % (m.group(1), m.group(2))
    elif re.fullmatch(r"\d+", tok):
        s = "(&%s)" % tok
    else:
        raise ValueError("bad rational: %r" % tok)
    return "(--%s)" % s if neg else s

def extract(grid):
    path = os.path.join(SRC, "AngleData%d.lean" % grid)
    pat = re.compile(r"^def angle%d_(\d+) : AngleEnclosure := ⟨(.*)⟩\s*$" % grid)
    rows = {}
    for line in open(path, encoding="utf-8"):
        m = pat.match(line)
        if m:
            fields = m.group(2).split(",")
            assert len(fields) == 7, line
            rows[int(m.group(1))] = [hol_rat(f) for f in fields]
        if line.startswith("theorem angle%d_" % grid):
            assert "decide +kernel" in line, line
    n = len(rows)
    assert sorted(rows) == list(range(n)), "indices not contiguous"
    # the Lean list angles<grid> must be exactly angle<grid>_0 .. _{n-1} in order
    text = open(path, encoding="utf-8").read()
    m = re.search(r"def angles%d : List \{w : AngleEnclosure // w.Check\} := \[(.*)\]" % grid, text)
    names = re.findall(r"⟨(angle%d_\d+),angle%d_\d+_checked⟩" % (grid, grid), m.group(1))
    assert names == ["angle%d_%d" % (grid, k) for k in range(n)], "list order"
    assert ("theorem angles%d_cover : CoversInterval 0 1 (angles%d.map Subtype.val)" % (grid, grid)) in text
    return [rows[k] for k in range(n)]

def emit(grid, rows):
    n = len(rows)
    tag = "AD%d" % grid
    terms = ["AngleEnc " + " ".join(r) for r in rows]
    lines = []
    lines.append("(* " + "=" * 73 + " *)")
    lines.append("(* Port of source/S12/AngleData%d.lean (Jatloe, N12-jatloe).%s*)" % (grid, " " * (17 - len(str(grid)))))
    lines.append("(* GENERATED by n12/scripts/angle_extract.py -- do not edit.                   *)")
    lines.append("(* angles%d is Lean's angles%d (as a list of AngleEnclosure values; the    *)" % (grid, grid))
    lines.append("(* subtype proofs angle%d_k_checked are ANGLE%d_CHECKED.(k)).               *)" % (grid, grid))
    lines.append("(* " + "=" * 73 + " *)")
    lines.append("")
    lines.append('needs "n12/geometry/p2_base.ml";;')
    lines.append('needs "n12/certlib/IntervalCoverage.ml";;')
    lines.append("")
    lines.append("(* Lean: angle%d_0 .. angle%d_%d (as OCaml terms) *)" % (grid, grid, n - 1))
    lines.append("let angle%d_tm = Array.of_list (map parse_term [" % grid)
    for k, t in enumerate(terms):
        lines.append('  "%s"%s' % (t, ";" if k < n - 1 else ""))
    lines.append("]);;")
    lines.append("")
    lines.append("(* Lean: angles%d *)" % grid)
    lines.append("let angles%d = new_definition" % grid)
    lines.append(" (mk_eq(mk_var(\"angles%d\",`:angle_enc list`)," % grid)
    lines.append("        mk_list(Array.to_list angle%d_tm,`:angle_enc`)));;" % grid)
    lines.append("")
    lines.append("(* Lean: angle%d_k_checked, k = 0..%d *)" % (grid, n - 1))
    lines.append("let ANGLE%d_CHECKED =" % grid)
    lines.append("  Array.map (fun tm -> AE_CHECK_RULE (mk_comb(`ae_check`,tm))) angle%d_tm;;" % grid)
    lines.append("")
    lines.append("let %s_ALL_CHECKED = prove" % tag)
    lines.append(" (`ALL ae_check angles%d`," % grid)
    lines.append("  REWRITE_TAC[angles%d; ALL] THEN REWRITE_TAC(Array.to_list ANGLE%d_CHECKED));;" % (grid, grid))
    lines.append("")
    lines.append("let %s_LENGTH = prove" % tag)
    lines.append(" (`LENGTH angles%d = %d`," % (grid, n))
    lines.append("  REWRITE_TAC[angles%d; LENGTH] THEN CONV_TAC NUM_REDUCE_CONV);;" % grid)
    lines.append("")
    lines.append("(* the indexed family: enclosure k of the %d-grid is checked *)" % grid)
    lines.append("let ANGLES%d_CHECKED = prove" % grid)
    lines.append(" (`!k. k < %d ==> ae_check (EL k angles%d)`," % (n, grid))
    lines.append("  REPEAT STRIP_TAC THEN MP_TAC %s_ALL_CHECKED THEN" % tag)
    lines.append("  REWRITE_TAC[GSYM ALL_MEM] THEN DISCH_THEN MATCH_MP_TAC THEN")
    lines.append("  MATCH_MP_TAC MEM_EL THEN ASM_REWRITE_TAC[%s_LENGTH]);;" % tag)
    lines.append("")
    lines.append("let %s_EL = prove" % tag)
    lines.append(" (list_mk_conj(map (fun k -> mk_eq(mk_comb(mk_comb(`EL:num->angle_enc list->angle_enc`,")
    lines.append("     mk_small_numeral k),`angles%d`), angle%d_tm.(k))) (0--%d)),"  % (grid, grid, n - 1))
    lines.append("  REWRITE_TAC[angles%d] THEN CONV_TAC(ONCE_DEPTH_CONV EL_CONV) THEN REWRITE_TAC[]);;" % grid)
    lines.append("")
    lines.append("(* Lean: angles%d_cover *)" % grid)
    lines.append("let ANGLES%d_COVER = prove" % grid)
    lines.append(" (`covers_interval (&0) (&1) angles%d`," % grid)
    lines.append("  REWRITE_TAC[angles%d] THEN" % grid)
    lines.append("  CONV_TAC(REWRITE_CONV[covers_interval; ae_lower; ae_upper] THENC")
    lines.append("           REAL_RAT_REDUCE_CONV THENC REWRITE_CONV[]));;")
    lines.append("")
    path = os.path.join(OUT, "AngleData%d.ml" % grid)
    open(path, "w").write("\n".join(lines))
    print("wrote", path, n, "enclosures")

if __name__ == "__main__":
    which = sys.argv[1] if len(sys.argv) > 1 else "all"
    grids = [64, 128] if which == "all" else [int(which)]
    for g in grids:
        emit(g, extract(g))
