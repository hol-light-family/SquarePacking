#!/usr/bin/env python3
"""gen_c983_components.py NN : write n12/geometry/CP_OtherCases_C983_ComponentsNN.ml from
Compact/Completion/OtherCases/C983/ComponentsNN.lean (untrusted generator in the style of the
hand ports Components03/08; HOL re-proves every domain)."""
import re, sys
L = 'n12/ext/jatloe/Lean/Proofs/N12-jatloe/Compact/Completion/OtherCases/C983/'
OUT = 'n12/geometry/'

def sets(s):
    s = s.strip()
    if s in ('∅', '{}'): return []
    assert s[0] == '{' and s[-1] == '}', s
    return [int(x) for x in s[1:-1].split(',') if x.strip()]
def setlist(s):
    s = s.strip(); assert s[0] == '[' and s[-1] == ']', s
    return [sets(x) for x in re.findall(r'∅|\{[\d,]*\}', s)]
def hol_sets(L):
    return '`[' + '; '.join('({}:num->bool)' if not x else '{' + ','.join(map(str, x)) + '}' for x in L) + ']`'
def ocl(x): return '[' + '; '.join(map(str, x)) + ']'

for nn in sys.argv[1:]:
    n = int(nn)
    src = open(L + 'Components%s.lean' % nn).read()
    imports = re.findall(r'^import (\S+)', src, re.M)
    tag = 'c983c%s' % nn; TAG = tag.upper()
    needs = ['CP_OtherCases_C983_RowIdentity', 'CP_OtherCases_MonotoneRefinement', 'CP_OtherCases_DomainCache',
             'SharedLocalQueries']
    for i in imports:
        p = i.split('.')
        if p[1] == 'HistoricalOwnership': needs.append(p[-1])
        if p[1] == 'Cases' and p[2] == 'C713': needs.append(p[-1])
        if p[-1] == 'MergedHullQuery': needs.append('CP_OtherCases_C983_MergedHullQuery')
    merged = False
    def query(tok):
        global merged
        tok = tok.strip()
        m = re.match(r'\(certified_query% (\d+)\)$', tok)
        if m: return m.group(1)
        m = re.match(r'N12Compact\.HistoricalOwnership\.Queries\.query(\d+)_certified$', tok)
        if m: return 'slq_hist_idx %s' % m.group(1)
        m = re.match(r'⟨S12\.query713_(\d+),S12\.query713_\1_checked⟩$', tok)
        if m: return 'c713eq_idx %s' % m.group(1)
        if tok == 'mergedF3G6_certified':
            merged = True; return '%s_merged_idx' % tag
        raise ValueError(tok)
    out = ['(* ========================================================================= *)',
           '(* Phase 2: Compact/Completion/OtherCases/C983/Components%s.lean' % nn,
           '   (namespace N12Compact.Completion.OtherCases.C983).  Same structure and toolkit',
           '   as Components03 / Components08: certified_query% n = local query n;',
           '   HistoricalOwnership queryN_certified = slq_hist_idx N (QueriesNNN.ml);',
           '   S12.query713_N = c713eq_idx N (C713/EntryQueryNN.ml); mergedF3G6_certified =',
           '   C983MHQ_MERGEDF3G6 registered under the local index ' + tag + '_merged_idx;',
           '   signature = mq_signature (Exact = ' + tag + '_exact); SingleDomain = dsd record,',
           '   Check = mq_single, product = pk_product, trim = mr_trim, diameterFilter =',
           '   mr_diameter_filter, cache = dc_cache, NamedDomain = dt_named.',
           '   family = c983ri_family.  Generated by n12/scripts/gen_c983_components.py.',
           '   Tag ' + tag + '_ / ' + TAG + '_.  *)',
           '(* ========================================================================= *)', '']
    out += ['needs "n12/geometry/%s.ml";;' % x for x in needs] + ['']
    body = []
    body += ['(* Lean signatures = queries.map signature (the Exact decides) *)',
             'let %s_exact sigs qs =' % tag,
             '  let norm (m, k, ow, bl) = (m, k, List.sort compare ow, List.sort compare bl) in',
             '  if map norm sigs <> map (fun q -> norm (mq_signature q)) qs then failwith "%s_exact";;' % tag, '']
    def qlist(name):
        m = re.search(r'private def %s%d : List \{q : LocalQuery // q\.Check\} :=\s*\[(.*?)\]\n' % (name, n), src, re.S)
        toks, depth, cur = [], 0, ''
        for ch in m.group(1):
            if ch in '⟨(': depth += 1
            if ch in '⟩)': depth -= 1
            if ch == ',' and depth == 0: toks.append(cur); cur = ''
            else: cur += ch
        toks.append(cur)
        return [query(t) for t in toks]
    def sigs(name):
        m = re.search(r'private def %s%d : List Signature :=\s*\[(.*?)\]\n' % (name, n), src, re.S)
        r = []
        for a, b, c, d in re.findall(r'\((\d+),(\d+),(∅|\{[\d,]*\}),(∅|\{[\d,]*\})\)', m.group(1)):
            r.append('(%s, %s, %s, %s)' % (a, b, ocl(sets(c)), ocl(sets(d))))
        return r
    for half, k in (('f', 0), ('g', 1)):
        qs = qlist(half + 'Queries'); sg = sigs(half + 'Signatures')
        assert len(qs) == len(sg)
        m = re.search(r'private def %sSingle%d : SingleDomain :=\s*⟨(\d+),(\d+),(\d+),(\[.*?\]),%sQueries%d⟩' % (half, n, half, n), src, re.S)
        mask, lo, hi, al = m.groups()
        assert re.search(r'%sSingle%d\.Check family %d %sSignatures%d' % (half, n, k, half, n), src)
        body += ['(* Lean: %sQueries%d (private) *)' % (half, n),
                 'let %s_%s_queries : int list = [%s];;' % (tag, half, '; '.join(qs)),
                 '(* Lean: %sSignatures%d (private) *)' % (half, n),
                 'let %s_%s_signatures : (int * int * int list * int list) list =' % (tag, half),
                 '  [' + ';\n   '.join(sg) + '];;',
                 '(* Lean: %sExact%d (private) *)' % (half, n),
                 'let () = %s_exact %s_%s_signatures %s_%s_queries;;' % (tag, tag, half, tag, half),
                 '(* Lean: %sSingle%d (private) *)' % (half, n),
                 'let %s_%s_single =' % (tag, half),
                 '  {dmask = %s; dlower = %s; dupper = %s; dallowed = [%s]; dqueries = %s_%s_queries};;'
                 % (mask, lo, hi, '; '.join(ocl(x) for x in setlist(al)), tag, half),
                 '(* Lean: %sChecked%d (private) *)' % (half, n),
                 'let %s_%s_CHECKED = mq_single `c983ri_family` %d %s_%s_single;;' % (TAG, half.upper(), k, tag, half), '']
    m = re.search(r'private def cachedProduct%d : CertifiedDomain family :=\s*DomainTransport\.cache rawDomain%d (\d+)\s*(\[.*?\]) \(by rfl\)' % (n, n), src, re.S)
    cmask, cal = m.groups()
    body += ['(* Lean: rawDomain%d (private) *)' % n,
             'let %s_RAW_DOMAIN =' % TAG,
             '  if %s_f_single.dmask <> %s_g_single.dmask then failwith "%s: masks" else' % (tag, tag, tag),
             '  pk_product %s_F_CHECKED %s_G_CHECKED;;' % (TAG, TAG),
             '(* Lean: cachedProduct%d (private) *)' % n,
             'let %s_CACHED_PRODUCT = dc_cache %s_RAW_DOMAIN %s' % (TAG, TAG, cmask),
             '  %s;;' % hol_sets(setlist(cal)), '']
    qs = qlist('combinedQueries'); sg = sigs('combinedSignatures')
    assert len(qs) == len(sg)
    body += ['(* Lean: combinedQueries%d, combinedSignatures%d, combinedExact%d (private) *)' % (n, n, n),
             'let %s_combined_queries : int list = [%s];;' % (tag, '; '.join(qs)),
             'let %s_combined_signatures : (int * int * int list * int list) list =' % tag,
             '  [' + ';\n   '.join(sg) + '];;',
             'let () = %s_exact %s_combined_signatures %s_combined_queries;;' % (tag, tag, tag), '',
             '(* Lean: filtered%d (private) *)' % n,
             'let %s_FILTERED = mr_diameter_filter (mr_trim %s_CACHED_PRODUCT %s_combined_queries);;' % (TAG, TAG, tag), '']
    m = re.search(r'def initial%d : DomainTransport\.NamedDomain family :=\s*⟨DomainTransport\.cache filtered%d (\d+)\s*(\[.*?\]) \(by rfl\)' % (n, n), src, re.S)
    imask, ial = m.groups()
    body += ['(* Lean: initial%d *)' % n,
             'let %s_INITIAL = dt_named (dc_cache %s_FILTERED %s' % (TAG, TAG, imask),
             '  %s);;' % hol_sets(setlist(ial))]
    if merged:
        out += ['(* mergedF3G6_certified under a local query index (data as in MergedHullQuery.ml) *)',
                'let %s_merged_idx = 3000983;;' % tag,
                'let () =',
                '  let d = (2304, 2, [3; 16],',
                '    [(nlin_rat "33/20", nlin_rat "33/20"); (nlin_rat "8/5", nlin_rat "3"); (nlin_rat "113/50", nlin_rat "2")],',
                '    [(nlin_rat "2", nlin_rat "113/50")]) in',
                '  let (m, k, ow, uin, uout) = d in',
                '  if concl (slq_new d) <> concl C983MHQ_MERGEDF3G6 then failwith "%s: merged" else' % tag,
                '  (Hashtbl.replace SLQ_HIST %s_merged_idx (%s_merged_idx, m, k, ow, uin, uout);' % (tag, tag),
                '   Hashtbl.replace SLQ_TBL %s_merged_idx (m, k, ow, C983MHQ_MERGEDF3G6));;' % tag, '']
    open(OUT + 'CP_OtherCases_C983_Components%s.ml' % nn, 'w').write('\n'.join(out + body) + '\n')
    print(nn, 'ok', needs)
