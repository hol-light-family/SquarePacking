# generates n12/geometry/CP_OtherCases_C715_RefinedDomains.ml from the Lean file
import re
R = ''
s = open(R + 'n12/ext/jatloe/Lean/Proofs/N12-jatloe/Compact/Completion/OtherCases/C715/RefinedDomains.lean').read()
def numsets(txt):
    return '[' + '; '.join('{%s}' % ', '.join(m.group(1).split(',')) if m.group(1) else '({}:num->bool)'
                           for m in re.finditer(r'\{([\d,]*)\}|∅', txt)) + ']'
out = ['''(* ========================================================================= *)
(* Phase 2: Compact/Completion/OtherCases/C715/RefinedDomains.lean.          *)
(* Literal domain cuts after each refinement stage.  A NamedDomain is the    *)
(* pair (|- cdom c715ri_family m al, |- m IN c715ri_family);                 *)
(*   cacheNamed (L.foldl NamedDomain.refine d) mask al =                     *)
(*     dc_cache_named (List.fold_left dt_refine d L) mask `al`               *)
(* (dt_refine = NamedDomain.refine via refineAgainst; dc_cache checks that   *)
(* every surviving allowed set is listed).  stage1Named / stage2Named are    *)
(* OCaml lists; domains (= stage2Named.map val) is C715RD_DOMAINS.           *)
(* Generated by n12/scripts/gen/gen_c715_refined.py.  Tag C715RD_.              *)
(* ========================================================================= *)

needs "n12/geometry/CP_OtherCases_C715_InitialDomains.ml";;
''']
ent = re.findall(r'def (stage(\d)Owner(\d+)) : NamedDomain family :=\s*cacheNamed \((\w+)\.foldl NamedDomain\.refine (\w+)\) (\d+)\s*(\[.*?\])\s*\(by decide \+kernel\) \(by decide \+kernel\)', s, re.S)
assert len(ent) == 24 == s.count(': NamedDomain family :=')
ref = {'initialNamed': 'C715ID_INITIAL_NAMED', 'stage1Named': 'C715RD_STAGE1_NAMED'}
cur = None
for name, st, i, lst, start, mask, al in ent:
    if st != cur and cur is not None:
        out.append('(* Lean: stage%sNamed *)' % cur)
        out.append('let C715RD_STAGE%s_NAMED = [%s];;\n' % (cur, '; '.join('C715RD_STAGE%sOWNER%d' % (cur, j) for j in range(12))))
    cur = st
    st_start = 'C715ID_' + start.upper() if start.startswith('initial') else 'C715RD_' + start.upper()
    out.append('(* Lean: %s *)' % name)
    out.append('let C715RD_%s = dc_cache_named (List.fold_left dt_refine %s %s) %s\n  `%s`;;' % (name.upper(), st_start, ref[lst], mask, numsets(al)))
out.append('(* Lean: stage2Named *)')
out.append('let C715RD_STAGE2_NAMED = [%s];;\n' % '; '.join('C715RD_STAGE2OWNER%d' % j for j in range(12)))
out.append('(* Lean: domains *)')
out.append('let C715RD_DOMAINS = map fst C715RD_STAGE2_NAMED;;')
open(R + 'n12/geometry/CP_OtherCases_C715_RefinedDomains.ml', 'w').write('\n'.join(out) + '\n')
