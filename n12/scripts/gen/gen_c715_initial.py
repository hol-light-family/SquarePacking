# generates n12/geometry/CP_OtherCases_C715_InitialDomains.ml from the Lean file
import re
R = ''
L = R + 'n12/ext/jatloe/Lean/Proofs/N12-jatloe/Compact/Completion/OtherCases/C715/InitialDomains.lean'
s = open(L).read()
alias, newq, extra = {}, {}, []
for i in range(4):
    t = open(R + 'n12/geometry/EntryQuery%02d.ml' % i).read()
    for k, n in re.findall(r'let C713EQ\d\d_QUERY713_(\d+) = slq_select (\d+);;', t):
        alias[int(k)] = int(n)
    for nm, k, d in re.findall(r'let (C713EQ\d\d_QUERY713_(\d+)) = slq_new \((.*?)\);;', t, re.S):
        newq[int(k)] = (nm, d)
reg = set(int(k) for k in re.findall(r'c713eq_register (\d+)', open(R + 'n12/geometry/Cases_C713_EntryQueries.ml').read()))
def qref(k):
    if k in alias: return str(alias[k])
    if k < 256 and k not in reg:
        nm, d = newq[k]
        extra.append('let _ = let (m, k, ow, uin, uout) = (%s) in c713eq_register %d (0, m, k, ow, uin, uout) %s;;' % (d, k, nm))
    return 'c713eq_idx %d' % k
def numsets(txt):
    out = []
    for m in re.finditer(r'\{([\d,]*)\}|∅', txt):
        out.append('{%s}' % ', '.join(m.group(1).split(',')) if m.group(1) else '{}')
    return '[' + '; '.join(out) + ']'
out = ['''(* ========================================================================= *)
(* Phase 2: Compact/Completion/OtherCases/C715/InitialDomains.lean.          *)
(* Genuine auxiliary entrance for original C715 (family c715ri_family).     *)
(* Lean CertifiedDomain family values are theorems |- cdom c715ri_family m al: *)
(*   .ofDirectProduct _ w0 w1 (rebase w0 ..) (rebase w1 ..) _  =             *)
(*       pk_product (dt_rebase fam 0 w0) (dt_rebase fam 1 w1)                *)
(*   (the C713 single domains c713eqs_single713_i_k re-checked, budgets      *)
(*   included, against the C715 family);                                     *)
(*   .remove _ d query713_k _ = slq_remove d n, n the index of query713_k     *)
(*   (slq_select N for an alias of localQueryN, else c713eq_idx k);          *)
(*   mask 17408: pk_product of MergedQueries.mergedF_checked / mergedG_checked.*)
(* initialN : NamedDomain = dt_named (dc_cache d mask allowed); initialNamed *)
(* is the OCaml list C715ID_INITIAL_NAMED.  Generated by                     *)
(* n12/scripts/gen/gen_c715_initial.py.  Tag C715ID_.                           *)
(* ========================================================================= *)

needs "n12/geometry/CP_OtherCases_C715_MergedQueries.ml";;
needs "n12/geometry/CP_OtherCases_DomainCache.ml";;
needs "n12/geometry/Cases_C713_EntryQueries.ml";;

let C715ID_FAM = `c715ri_family`;;
''', 'EXTRA']
defs = re.findall(r'def (domain715_\d+_\d+) : CertifiedDomain family :=\s*(.*?)\n\n', s, re.S)
for name, body in defs:
    body = ' '.join(body.split())
    out.append('(* Lean: %s *)' % name)
    m = re.match(r'\.ofDirectProduct _ (single713_\d+_0) (single713_\d+_1) \(rebase \1 case713Family family 0 \1_checked .*\) \(rebase \2 case713Family family 1 \2_checked .*\) \(by decide \+kernel\)$', body)
    if m:
        out.append('let C715ID_%s = pk_product (dt_rebase C715ID_FAM 0 c713eqs_%s)\n  (dt_rebase C715ID_FAM 1 c713eqs_%s);;' % (name.upper(), m.group(1), m.group(2)))
        continue
    m = re.match(r'\.remove _ (domain715_\d+_\d+) query713_(\d+) query713_\2_checked \(by decide \+kernel\) \(by decide \+kernel\)$', body)
    if m:
        out.append('let C715ID_%s = slq_remove C715ID_%s (%s);;' % (name.upper(), m.group(1).upper(), qref(int(m.group(2)))))
        continue
    m = re.match(r'\.ofDirectProduct _ mergedF mergedG mergedF_checked mergedG_checked \(by decide \+kernel\)$', body)
    assert m, body
    out.append('let C715ID_%s = pk_product C715MQ_MERGEDF_CHECKED C715MQ_MERGEDG_CHECKED;;' % name.upper())
assert len(defs) == s.count(': CertifiedDomain family :=')
inits = re.findall(r'def (initial\d+) : NamedDomain family :=\s*⟨cache (domain715_\d+_\d+) (\d+) (\[.*?\])\s*\(by decide \+kernel\) \(by decide \+kernel\),by decide \+kernel⟩', s, re.S)
assert len(inits) == 12 == s.count(': NamedDomain family :=')
out.append('')
for name, d, mask, al in inits:
    out.append('(* Lean: %s *)' % name)
    out.append('let C715ID_%s = dt_named (dc_cache C715ID_%s %s\n  `%s`);;' % (name.upper(), d.upper(), mask, numsets(al).replace('[', '[', 1)))
out.append('')
out.append('(* Lean: initialNamed *)')
out.append('let C715ID_INITIAL_NAMED : (thm * thm) list =\n  [%s];;' % '; '.join('C715ID_' + n.upper() for n, _, _, _ in inits))
i = out.index('EXTRA')
out[i:i+1] = (['(* literal EntryQuery00-03 queries used by remove, registered under c713eq_idx k *)'] + extra + ['']) if extra else []
open(R + 'n12/geometry/CP_OtherCases_C715_InitialDomains.ml', 'w').write('\n'.join(out) + '\n')
