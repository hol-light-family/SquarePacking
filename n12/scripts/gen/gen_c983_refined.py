# generates n12/geometry/CP_OtherCases_C983_RefinedDomains{K}.ml from the Lean file (K = 1, 2, 3)
import re, sys
R = ''
K = int(sys.argv[1])
s = open(R + 'n12/ext/jatloe/Lean/Proofs/N12-jatloe/Compact/Completion/OtherCases/C983/RefinedDomains%d.lean' % K).read()
def numsets(txt):
    return '[' + '; '.join('{%s}' % ', '.join(m.group(1).split(',')) if m.group(1) else '({}:num->bool)'
                           for m in re.finditer(r'\{([\d,]*)\}|∅', txt)) + ']'
prev = 'CP_OtherCases_C983_InitialDomains' if K == 1 else 'CP_OtherCases_C983_RefinedDomains%d' % (K - 1)
T = 'C983RD%d_' % K
out = ['''(* ========================================================================= *)
(* Phase 2: Compact/Completion/OtherCases/C983/RefinedDomains%d.lean.         *)
(* Literal domain cuts after refinement stage %d.  A NamedDomain is the       *)
(* pair (|- cdom c983ri_family m al, |- m IN c983ri_family);                 *)
(*   cacheNamed (L.foldl NamedDomain.refine d) mask al =                     *)
(*     dc_cache_named (List.fold_left dt_refine d L) mask `al`               *)
(* (dt_refine = NamedDomain.refine via refineAgainst; dc_cache checks that   *)
(* every surviving allowed set is listed; the mask equality is checked by   *)
(* dc_cache too).  stage%dNamed is an OCaml list.  initialK = EL K of        *)
(* C983ID_INITIAL_NAMED.                                                     *)
(* Generated by n12/scripts/gen/gen_c983_refined.py %d.  Tag %s.             *)
(* ========================================================================= *)

needs "n12/geometry/%s.ml";;
''' % (K, K, K, K, T, prev)]
ent = re.findall(r'def (stage(\d)Owner(\d+)) : NamedDomain family :=\s*cacheNamed \((\w+)\.foldl NamedDomain\.refine (\w+)\) (\d+)\s*(\[.*?\])\s*\(by decide \+kernel\) \(by decide \+kernel\)', s, re.S)
assert len(ent) == 12 == s.count(': NamedDomain family :=')
if K == 1:
    ref = {'initialNamed': 'C983ID_INITIAL_NAMED'}
else:
    ref = {'stage%dNamed' % (K - 1): 'C983RD%d_STAGE%d_NAMED' % (K - 1, K - 1)}
for j, (name, st, i, lst, start, mask, al) in enumerate(ent):
    assert int(st) == K and int(i) == j
    if K == 1:
        assert start == 'initial%d' % j
        st_start = 'List.nth C983ID_INITIAL_NAMED %d' % j
    else:
        assert start == 'stage%dOwner%d' % (K - 1, j)
        st_start = 'C983RD%d_STAGE%dOWNER%d' % (K - 1, K - 1, j)
    out.append('(* Lean: %s *)' % name)
    out.append('let %s%s = dc_cache_named (List.fold_left dt_refine (%s) %s) %s\n  `%s`;;' % (T, name.upper(), st_start, ref[lst], mask, numsets(al)))
assert re.search(r'def stage%dNamed : List \(NamedDomain family\) :=\s*\[%s\]' % (K, ','.join('stage%dOwner%d' % (K, j) for j in range(12))), s)
out.append('(* Lean: stage%dNamed *)' % K)
out.append('let %sSTAGE%d_NAMED = [%s];;' % (T, K, '; '.join('%sSTAGE%dOWNER%d' % (T, K, j) for j in range(12))))
open(R + 'n12/geometry/CP_OtherCases_C983_RefinedDomains%d.ml' % K, 'w').write('\n'.join(out) + '\n')
