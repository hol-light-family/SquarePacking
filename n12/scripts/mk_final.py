#!/usr/bin/env python3
"""Generate n12/make.ml: the single fresh-process build of  |- square_packing_side 12 = &4.

  python3 n12/scripts/mk_final.py            -> writes n12/make.ml
  shared/build.sh n12/make.ml   (run from the project root)

Contents (in order):
  1. n12/cases/cs_load.ml        Phase-1 chain and the case bridges
  2. n12/phase1/step6_run.ml     S12_REDUCED_117 (Phase-1 reduction to the 117 retained rows)
  3. every geometry file, in Lean dependency order (n12/scripts/done_order.py)
  4. n12/certlib (p3_all.ml) and the certificate layers -> CA_EXCLUDED (7 certificate cases)
  5. the case drivers (template cases, cs2 families, C868)
  6. the packing-level case theorems registered in n12/port_data/case_thms.txt
  7. n12/assembly.ml: S12_NO_PACKING, SQUARE_PACKING_SIDE_12, PACKS_12; hypothesis and axiom checks
  8. n12/statement.ml: the auditor-facing statement and its mechanical check
"""
import os, subprocess
R = '.'
os.chdir(R)
done = [l.strip() for l in subprocess.run(['python3', 'n12/scripts/done_order.py'], capture_output=True,
                                         text=True).stdout.splitlines() if l.strip() and not l.startswith('#')]
drivers = [('n12/cases/variant.ml', 'VARIANT_CASE_THMS'),
           ('n12/cases/foursquare.ml', 'FS_CASE_THMS'),
           ('n12/cases/highright.ml', 'HR_CASE_THMS'),
           ('n12/cases/cs2_all.ml', 'CS2_CASE_THMS'),
           ('n12/cases/c868.ml', 'C868_CASE_THMS')]
drivers = [(f, v) for f, v in drivers if os.path.exists(f)]
pack = []
for l in open('n12/port_data/case_thms.txt'):
    w = l.split()
    if len(w) >= 3 and os.path.exists('n12/geometry/' + w[1]):
        pack.append((int(w[0]), w[1], w[2]))
out = []
o = out.append
o('(* GENERATED by n12/scripts/mk_final.py -- the build of |- square_packing_side 12 = &4.            *)')
o('(* Run from the project root:  shared/build.sh n12/make.ml  (about 16 h, ~20 GB). *)')
o('(* The statement proved, and what its constants mean: n12/statement.ml.                       *)')
o('let fin_t0 = Sys.time ();;')
o('let fin_mark s = Printf.printf "FINAL %s: %.0fs\\n%!" s (Sys.time () -. fin_t0);;')
def stage(f, label):
    o('let () = try loadt "%s"; fin_mark "%s" with e -> (fin_mark ("STAGEFAIL %s: " ^ Printexc.to_string e));;' % (f, label, label))
o('loadt "n12/cases/cs_load.ml";;')
o('fin_mark "Phase-1 chain";;')
stage('n12/phase1/step6_run.ml', 'Phase-1 reduction (S12_REDUCED_117)')
o('needs "n12/geometry/PackingContext.ml";;')
for f in done:
    o('let () = try needs "n12/geometry/%s.ml" with e -> fin_mark ("STAGEFAIL p2 %s: " ^ Printexc.to_string e);;' % (f, f))
o('fin_mark "p2 geometry (%d files)";;' % len(done))
# the certificate cases: certlib and the certificate layers
for f, lab in [('n12/certlib/p3_all.ml','p3'), ('n12/cert/CA_all.ml','cert stages'),
               ('n12/cert/CA_LoadOV.ml','overlaps'), ('n12/cert/PV_all.ml','initial covers'),
               ('n12/cert/CA_ProvidePV.ml','PV providers'), ('n12/cases/cert_cases.ml','cert cases')]:
    stage(f, lab)
o('needs "n12/cases/case_util.ml";;')
for f, v in drivers:
    stage(f, os.path.basename(f))
for (cid, f, name) in pack:
    o('needs "n12/geometry/%s";;' % f)
o('needs "n12/assembly.ml";;')
o('''(* a case theorem in either form |- EXCLUDED_ROW ri, or |- excl_case id (RowIdentity.ml) *)
let fin_excluded th =
  if hyp th <> [] then failwith "fin_excluded: hypotheses" else
  try let ri = find (fun ri -> aconv (concl th) (EXCLUDED_ROW ri)) RETAINED_IDX in (ri, th)
  with Failure _ -> tryfind (fun ri -> let t = ri_excluded_row ri th in (ri, t)) RETAINED_IDX;;''')
# one phrase per contribution: an unbound name only drops that contribution
o('let FIN_ALL = ref ([] : thm list);;')
o('let fin_add name ths = FIN_ALL := !FIN_ALL @ ths; Printf.printf "FINAL add %s: %d\\n%!" name (length ths);;')
for f, v in drivers:
    o('fin_add "%s" (map snd %s);;' % (v, v))
o('fin_add "CA_EXCLUDED" (map (fun (_, _, th) -> th) (filter (fun (_, _, th) -> hyp th = []) CA_EXCLUDED));;')
for (cid, f, name) in pack:
    o('fin_add "%s" [snd (fin_excluded %s)];;' % (name, name))
o('let S12_NO_PACKING = s12_no_packing !FIN_ALL;;')
o('let SQUARE_PACKING_SIDE_12 = MP S12_SIDE_OF_NO_PACKING S12_NO_PACKING;;')
o('let PACKS_12 = MP PACKS_12_OF_NO_PACKING S12_NO_PACKING;;')
o('let S12_SIDE = SQUARE_PACKING_SIDE_12;;')
o('fin_mark "assembled";;')
o('Printf.printf "FINAL hypotheses remaining: %d\\n%!" (length (hyp S12_SIDE));;')
o('SQUARE_PACKING_SIDE_12;;')
o('PACKS_12;;')
o('axioms();;')
# one phrase each, so that a failure cannot be followed by a misleading "passed" line (the build is piped
# into the toplevel, where an exception only aborts the current phrase) [audit 2026-11-13]
o('let () = if hyp S12_SIDE <> [] || concl S12_SIDE <> `square_packing_side 12 = &4` then print_string "FINAL RESULT CHECK FAILED: hypotheses or wrong statement\\n" else print_string "FINAL RESULT CHECK passed: |- square_packing_side 12 = &4 with no hypotheses\\n";;')
o('let () = try check_axioms (); print_string "FINAL check_axioms passed: only INFINITY_AX, SELECT_AX, ETA_AX\\n" with Failure s -> print_string ("FINAL check_axioms FAILED: " ^ s ^ "\\n");;')
o('loadt "n12/statement.ml";;')
open('n12/make.ml', 'w').write('\n'.join(out) + '\n')
print('n12/make.ml: %d p2 files, %d drivers, %d packing-level case theorems' % (len(done), len(drivers), len(pack)))
