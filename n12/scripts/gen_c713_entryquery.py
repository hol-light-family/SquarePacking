#!/usr/bin/env python3
"""gen_c713_entryquery.py NN... : write n12/geometry/EntryQueryNN.ml from
Compact/Cases/C713/EntryQueryNN.lean (untrusted generator; HOL re-proves every query).
query713_N := localQueryK  ->  slq_select K   (the Phase-1 query, re-proved by the kernel;
                                c713_query_at queryChunkC _ <i> is checked to name K = 50*C+i)
query713_N := <new data>    ->  slq_new (mask, kind, owned, inside, outside) with the hint points
                                of n12/data/cert/entry_queries.txt (n12/scripts/cert_extract_entry.py)."""
import re, sys
L = 'n12/ext/jatloe/Lean/Proofs/N12-jatloe/Compact/Cases/C713/'
OUT = 'n12/geometry/'
new = {}
for line in open('n12/data/cert/entry_queries.txt'):
    f = line.split()
    if f[0].startswith('C713_'):
        new[int(f[0][5:])] = f[1:]
def pl(s):
    if s == '-': return '[]'
    return '[' + '; '.join('(nlin_rat "%s", nlin_rat "%s")' % tuple(p.split(',')) for p in s.split(';')) + ']'
for nn in sys.argv[1:]:
    src = open(L + 'EntryQuery%s.lean' % nn).read()
    out = ['(* ========================================================================= *)',
           '(* Phase 2: Compact/Cases/C713/EntryQuery%s.lean (namespace S12).%s*)' % (nn, ' ' * 9),
           '(* C713 entry queries query713_N with their checks query713_N_checked.     *)',
           '(* A query equal to S12 localQueryK (Lean c713_query_at queryChunkC ..) is  *)',
           '(* slq_select K: the Phase-1 local query K re-proved by the kernel; a new   *)',
           '(* query (.hull / .four certificate) is slq_new (mask, kind, owned, inside, *)',
           '(* outside) with its certificate points (SharedLocalQueries.ml).  Each      *)',
           '(* QUERY713_N_CHECKED is the LocalQuery.sound theorem of the query.        *)',
           '(* Generated by n12/scripts/gen_c713_entryquery.py.  Tag QUERY713_.             *)',
           '(* ========================================================================= *)',
           '', 'needs "n12/geometry/Cases_C713_EntryQueryBase.ml";;', '',
           '(* every query713_N is also registered under the index c713eq_idx N, so that',
           '   index-based tools (slq_data, slq_select, mq_signature, dqueries) can use it *)',
           'let c713eq_idx n = 2000000 + n;;',
           'let c713eq_register n (_, m, k, ow, uin, uout) th =',
           '  let i = c713eq_idx n and ow = List.sort compare ow in',
           '  Hashtbl.replace SLQ_HIST i (i, m, k, ow, uin, uout);',
           '  Hashtbl.replace SLQ_TBL i (m, k, ow, th); th;;', '']
    n = 0
    for m in re.finditer(r'def query713_(\d+) : LocalQuery := (.*)\ntheorem query713_\1_checked : query713_\1\.Check :=(.*)\n(  c713_query_at queryChunk(\d+) queryChunk\5_checked ⟨(\d+), by decide⟩\n)?', src):
        q, body, rest, _, chunk, idx = m.groups()
        q = int(q); n += 1
        lm = re.match(r'localQuery(\d+)$', body.strip())
        if lm:
            k = int(lm.group(1))
            assert chunk is not None and 50 * int(chunk) + int(idx) == k, (q, k, chunk, idx)
            out += ['(* Lean: query713_%d, query713_%d_checked (localQuery%d) *)' % (q, q, k),
                    'let QUERY713_%d_CHECKED = let (_, _, _, th) = slq_select %d in c713eq_register %d (slq_data %d) th;;' % (q, k, q, k)]
        else:
            assert 'decide +kernel' in rest, q
            mask, kind, owned, ins, outs = new[q]
            ow = '[]' if owned == '-' else '[' + '; '.join(owned.split(',')) + ']'
            out += ['(* Lean: query713_%d, query713_%d_checked *)' % (q, q),
                    'let QUERY713_%d_CHECKED = let d = (%s, %s, %s,' % (q, mask, kind, ow),
                    '  %s,' % pl(ins), '  %s) in' % pl(outs),
                    '  let (m, k, ow, uin, uout) = d in c713eq_register %d (0, m, k, ow, uin, uout) (slq_new d);;' % q]
    assert n == src.count('def query713_'), (nn, n)
    open(OUT + 'EntryQuery%s.ml' % nn, 'w').write('\n'.join(out) + '\n')
    print(nn, n)
