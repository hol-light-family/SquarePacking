(* Lean: components_original *)
let C983E_COMPONENTS_ORIGINAL =
  let als = dest_list (rhs (concl c983e_domain_allowed)) in
  let ocs = dest_list (rhs (concl c983e_original_components)) in
  let ths = map2 all_mem_thm als ocs in
  let all2 = prove
   (`ALL2 (\al oc. ALL (\s. MEM s oc) al) c983e_domain_allowed c983e_original_components`,
    REWRITE_TAC[c983e_domain_allowed; c983e_original_components; ALL2] THEN
    CONV_TAC(ONCE_DEPTH_CONV BETA_CONV) THEN REWRITE_TAC ths) in
  let len = (REWRITE_CONV[c983e_domain_allowed; LENGTH] THENC NUM_REDUCE_CONV) `LENGTH c983e_domain_allowed` in
  prove
   (`forall i s. i < 12 /\ MEM s (EL i c983e_domain_allowed) ==> MEM s (EL i c983e_original_components)`,
    REPEAT STRIP_TAC THEN
    MP_TAC(ISPECL [`\al oc. ALL (\s:num->bool. MEM s oc) al`; `c983e_domain_allowed`;
                   `c983e_original_components`; `i:num`] C983E_ALL2_EL) THEN
    ASM_REWRITE_TAC[all2; len] THEN BETA_TAC THEN REWRITE_TAC[GSYM ALL_MEM] THEN
    DISCH_THEN MATCH_MP_TAC THEN ASM_REWRITE_TAC[]);;

(* Lean: owners  (the 5-tuple of the owner at ownerCode i) *)
let c983e_own i =
  let m = mk_comb(mk_comb(`EL:num->(num)list->num`, i), `c983ri_owner_code`) in
  map (fun f -> list_mk_comb(f, C983E_VARS @ [m])) [`ooc`; `oos`; `oou`; `oov`] @ [`l:real`];;

(* Lean: actual *)
let c983e_actual = new_definition
 `c983e_actual c1 c2 a b l (i:num) = ooaux c1 c2 a b l (EL i c983ri_owner_code)`;;

(* Lean: owner_code *)
let C983E_OWNER_CODE = prove
 (`forall c1 c2 a b l i. NPACK c1 c2 a b l /\ IMAGE binarysum (FFP c1 c2 a b l) = c983ri_family /\ i < 12
     ==> ownmask (c1 (oidx c1 c2 a b l (EL i c983ri_owner_code))) (c2 (oidx c1 c2 a b l (EL i c983ri_owner_code)))
                 (a (oidx c1 c2 a b l (EL i c983ri_owner_code))) (b (oidx c1 c2 a b l (EL i c983ri_owner_code))) l =
         EL i c983ri_owner_code`,
  REPEAT STRIP_TAC THEN
  MP_TAC(SPECL (C983E_VARS @ [C983E_F; `EL i c983ri_owner_code`]) OO_CODE) THEN
  ASM_SIMP_TAC[C983E_MEMBER]);;

(* Lean: actual_mem *)
let C983E_ACTUAL_MEM = prove
 (`forall c1 c2 a b l i. NPACK c1 c2 a b l /\ IMAGE binarysum (FFP c1 c2 a b l) = c983ri_family /\ i < 12
     ==> MEM (c983e_actual c1 c2 a b l i) (EL i c983e_domain_allowed)`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[c983e_actual] THEN MATCH_MP_TAC CDOM_OWNER THEN
  EXISTS_TAC C983E_F THEN ASM_SIMP_TAC[C983E_DOMAIN_MASK; C983E_MEMBER]);;

(* Lean: original_actual_mem *)
let C983E_ORIGINAL_ACTUAL_MEM = prove
 (`forall c1 c2 a b l i. NPACK c1 c2 a b l /\ IMAGE binarysum (FFP c1 c2 a b l) = c983ri_family /\ i < 12
     ==> MEM (c983e_actual c1 c2 a b l i) (EL i c983e_original_components)`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC C983E_COMPONENTS_ORIGINAL THEN
  ASM_SIMP_TAC[C983E_ACTUAL_MEM]);;

(* Lean: owners_side  (every owner has the common side l) *)
let C983E_OWNERS_SIDE = prove
 (`forall c1 c2 a b l. NPACK c1 c2 a b l ==> &1 < l`,
  REWRITE_TAC[OO_SIDE]);;

(* Lean: owners_cap *)
let C983E_OWNERS_CAP = prove
 (`forall c1 c2 a b l. NPACK c1 c2 a b l ==> l <= &1001 / &1000`,
  REWRITE_TAC[OO_SIDE_LE]);;

(* Lean: owners_same_side  (the side field of owners p i and owners p j is the same term l) *)
let C983E_OWNERS_SAME_SIDE = prove
 (`forall l:real. l = l`, REWRITE_TAC[]);;

(* Lean: owners_contained *)
let C983E_OWNERS_CONTAINED = prove
 (mk_forall(`c1:num->real`, list_mk_forall([`c2:num->real`; `a:num->real`; `b:num->real`; `l:real`; `i:num`],
   mk_imp(`NPACK c1 c2 a b l`, list_mk_comb(`lcont`, c983e_own `i:num`)))),
  SIMP_TAC[OO_BOX]);;

(* Lean: owners_markers *)
let C983E_OWNERS_MARKERS = prove
 (mk_forall(`c1:num->real`, list_mk_forall([`c2:num->real`; `a:num->real`; `b:num->real`; `l:real`; `i:num`],
   mk_imp(`NPACK c1 c2 a b l /\ IMAGE binarysum (FFP c1 c2 a b l) = c983ri_family /\ i < 12`,
     mk_forall(`k:num`, mk_imp(`k < 16`,
       mk_eq(list_mk_comb(`linside`, c983e_own `i:num` @ [`marker k$1`; `marker k$2`]),
             `k IN bitset (EL i c983ri_owner_code)`)))))),
  REPEAT GEN_TAC THEN STRIP_TAC THEN MATCH_MP_TAC OO_MARKERS THEN
  EXISTS_TAC C983E_F THEN ASM_SIMP_TAC[C983E_MEMBER]);;

(* Lean: codes_injective (private) *)
let C983E_CODES_INJECTIVE = prove
 (`forall i j. i < 12 /\ j < 12 /\ EL i c983ri_owner_code = EL j c983ri_owner_code ==> i = j`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC PAIRWISE_DISTINCT_EL THEN
  EXISTS_TAC `c983ri_owner_code` THEN ASM_REWRITE_TAC[C983E_LENGTH] THEN
  REWRITE_TAC[c983ri_owner_code; snd C983E_LIST]);;

(* Lean: owners_apart *)
let C983E_OWNERS_APART = prove
 (mk_forall(`c1:num->real`, list_mk_forall([`c2:num->real`; `a:num->real`; `b:num->real`; `l:real`; `i:num`; `j:num`],
   mk_imp(`NPACK c1 c2 a b l /\ IMAGE binarysum (FFP c1 c2 a b l) = c983ri_family /\ i < 12 /\ j < 12 /\ ~(i = j)`,
     list_mk_comb(`ldisj`, c983e_own `i:num` @ c983e_own `j:num`)))),
  REPEAT STRIP_TAC THEN MATCH_MP_TAC OO_LIST_APART THEN EXISTS_TAC C983E_F THEN
  ASM_REWRITE_TAC[C983E_LENGTH] THEN REWRITE_TAC[c983ri_owner_code] THEN
  REWRITE_TAC[fst C983E_LIST; snd C983E_LIST]);;

(* Lean: actual_disjoint *)
let C983E_ACTUAL_DISJOINT = prove
 (`forall c1 c2 a b l i j. NPACK c1 c2 a b l /\ IMAGE binarysum (FFP c1 c2 a b l) = c983ri_family /\
     i < 12 /\ j < 12 /\ ~(i = j)
     ==> DISJOINT (c983e_actual c1 c2 a b l i) (c983e_actual c1 c2 a b l j)`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[c983e_actual] THEN MATCH_MP_TAC OO_LIST_AUX_DISJOINT THEN
  EXISTS_TAC C983E_F THEN ASM_REWRITE_TAC[C983E_LENGTH] THEN REWRITE_TAC[c983ri_owner_code] THEN
  REWRITE_TAC[fst C983E_LIST; snd C983E_LIST]);;

(* Lean: auxiliary_inside *)
let C983E_AUXILIARY_INSIDE = prove
 (mk_forall(`c1:num->real`, list_mk_forall([`c2:num->real`; `a:num->real`; `b:num->real`; `l:real`; `i:num`; `j:num`],
   mk_imp(`j < 20 /\ j IN c983e_actual c1 c2 a b l i`,
     list_mk_comb(`linside`, c983e_own `i:num` @ [`EL j (AUXPTS 2)$1`; `EL j (AUXPTS 2)$2`])))),
  REWRITE_TAC[c983e_actual] THEN MESON_TAC[OO_AUX_EXACT]);;

(* Lean: seed_inside, as a producer at a literal index i < 12 and a point (x, y) of
   seedPoints (maskSupport (ownerCode i)) (checked by oo_seed; fails otherwise):
   |- !c1 c2 a b l. NPACK .. /\ IMAGE .. = c983ri_family
        ==> linside (owner (EL i c983ri_owner_code) at the literal mask) .. l x y *)
let c983e_seed_inside i (x, y) =
  if i < 0 || i >= 12 then failwith "c983e_seed_inside: index" else
  oo_inst C983E_F (oo_seed (el i C983E_MASKS) (x, y));;
