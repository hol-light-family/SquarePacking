(* Phase 2: Compact/Completion/OtherCases/C983/Entrance.lean.                *)
(* Every original C983 packing has its complete actual twenty-point          *)
(* ownership set in the certified component domains (stage 3 of the        *)
(* refinement), and these lie in the displayed originalComponents.          *)
(* Representation: family = c983ri_family, ownerCode i = EL i                *)
(* c983ri_owner_code (RowIdentity); domains i = EL i C983E_DOMAINS (OCaml    *)
(* list of |- cdom c983ri_family m al), (domains i).allowed = EL i           *)
(* c983e_domain_allowed; originalComponents i = EL i                          *)
(* c983e_original_components; owners p i = the OriginalOwners 5-tuple at    *)
(* mask EL i c983ri_owner_code (side l, c983e_own); actual p i =            *)
(* c983e_actual c1 c2 a b l i = ooaux c1 c2 a b l (EL i c983ri_owner_code).  *)
(* Fin 12 indices are i < 12.  (auxPoints 2)[j]! is EL j (AUXPTS 2).         *)
(* originalComponents generated by n12/scripts/gen/gen_c983_entrance.py.        *)
(* Tag C983E_ / c983e_.                                                       *)
(* ========================================================================= *)

needs "n12/geometry/CP_OtherCases_C983_RefinedDomains3.ml";;

let C983E_F = `c983ri_family`;;
let C983E_VARS = [`c1:num->real`; `c2:num->real`; `a:num->real`; `b:num->real`; `l:real`];;
let C983E_MASKS = [1; 2; 12; 48; 192; 512; 1024; 2304; 4096; 8192; 16384; 32768];;
if dest_list (rand (concl c983ri_owner_code)) <> map mk_small_numeral C983E_MASKS
then failwith "C983E: ownerCode";;

let C983E_ALL2_EL = prove
 (`forall P (l1:A list) (l2:B list) i. ALL2 P l1 l2 /\ i < LENGTH l1 ==> P (EL i l1) (EL i l2)`,
  GEN_TAC THEN LIST_INDUCT_TAC THEN LIST_INDUCT_TAC THEN REWRITE_TAC[ALL2; LENGTH; CONJUNCT1 LT] THEN
  GEN_TAC THEN STRUCT_CASES_TAC (SPEC `i:num` num_CASES) THEN
  REWRITE_TAC[EL; HD; TL; LT_SUC] THEN ASM_MESON_TAC[]);;

let C983E_LENGTH =
  (REWRITE_CONV[c983ri_owner_code; LENGTH] THENC NUM_REDUCE_CONV) `LENGTH c983ri_owner_code`;;
let C983E_LIST = oo_list_facts C983E_F (rand (concl c983ri_owner_code));;

let C983E_MEMBER = prove
 (`forall i. i < 12 ==> EL i c983ri_owner_code IN c983ri_family`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC OO_LIST_MEMBER THEN
  REWRITE_TAC[C983E_LENGTH; c983ri_owner_code] THEN ASM_REWRITE_TAC[fst C983E_LIST]);;

(* Lean: domains *)
let C983E_DOMAINS = map fst C983RD3_STAGE3_NAMED;;
if exists (fun th -> cdom_fam th <> C983E_F) C983E_DOMAINS then failwith "C983E: family";;

let c983e_domain_allowed = new_definition
  (mk_eq(`c983e_domain_allowed:((num->bool)list)list`,
         mk_list(map (fun th -> rand (concl th)) C983E_DOMAINS, `:(num->bool)list`)));;

(* Lean: domain_mask  ((domains i).mask = ownerCode i), as the checked domain at ownerCode i *)
let C983E_DOMAIN_MASK =
  if map cdom_mask C983E_DOMAINS <> C983E_MASKS then failwith "C983E: domain_mask" else
  let all2 = prove
   (`ALL2 (\m al. cdom c983ri_family m al) c983ri_owner_code c983e_domain_allowed`,
    REWRITE_TAC[c983ri_owner_code; c983e_domain_allowed; ALL2] THEN BETA_TAC THEN
    REWRITE_TAC C983E_DOMAINS) in
  prove
   (`forall i. i < 12 ==> cdom c983ri_family (EL i c983ri_owner_code) (EL i c983e_domain_allowed)`,
    REPEAT STRIP_TAC THEN
    MP_TAC(ISPECL [`\m al. cdom c983ri_family m al`; `c983ri_owner_code`; `c983e_domain_allowed`; `i:num`]
             C983E_ALL2_EL) THEN
    ASM_REWRITE_TAC[all2; C983E_LENGTH] THEN BETA_TAC THEN REWRITE_TAC[]);;

