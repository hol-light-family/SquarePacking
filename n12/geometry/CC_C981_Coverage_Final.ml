  if a = b then REFL a else
  if is_cons a && is_cons b then
    let h1, t1 = dest_cons a and h2, t2 = dest_cons b in
    MK_COMB(AP_TERM (rator (rator a)) (c981cf_teq h1 h2), c981cf_teq t1 t2)
