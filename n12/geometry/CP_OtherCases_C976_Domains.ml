(* the cover theorems: owner m in half k meets one of the aux points js *)
let c976d_cover hd k m js =
  let pts = map (fun j -> let th = SPECL [`c1:num->real`; `c2:num->real`; `a:num->real`; `b:num->real`;
                                       `l:real`; mk_small_numeral m] (oo_auxk_point k j) in
                          lhand (concl th)) js in
  let goal = list_mk_forall([`c1:num->real`; `c2:num->real`; `a:num->real`; `b:num->real`; `l:real`],
               mk_imp(C976D_PACK, list_mk_disj pts)) in
  prove(goal,
    REPEAT GEN_TAC THEN STRIP_TAC THEN
    REWRITE_TAC(map (oo_auxk_point k) js) THEN
    MP_TAC(MATCH_MP HDOM_OWNER (end_itlist CONJ
      [hd; ASSUME `NPACK c1 c2 a b l`;
       ASSUME `IMAGE binarysum (FFP c1 c2 a b l) = c976od_family`;
       in_fam m `c976od_family`])) THEN
    REWRITE_TAC[MEM] THEN REPEAT STRIP_TAC THEN ASM_REWRITE_TAC[IN_INSERT; NOT_IN_EMPTY] THEN
    CONV_TAC NUM_REDUCE_CONV);;

