(* register the translated Lean local queries *)
let () =
  List.iter (fun (m, k, ow, uin, uout) ->
    let known = Hashtbl.mem LQ_TABLE (m, k, ow) ||
      exists (fun (_, m', k', o', _, _) -> m' = m && k' = k && o' = ow) LOCAL_QUERIES in
    if not known then
      if k < 2 then Hashtbl.replace LQ_TABLE (m, k, ow) (query_theorem (-1, m, k, ow, uin, uout))
      else Hashtbl.replace PK_XQ (m, k, ow) (uin, uout))
  C976D_QUERIES;;

(* |- hdom c976od_family m k al  from the Lean allowed list of a direct single domain *)
let c976d_hdom k (m, lo, hi, al) =
  let th = spec_theorem m k lo hi al in
  let ownp = mk_eq(`owned c1 c2 a b l`, set_tm (bits m)) in
  let (hl, hh) = bound_tms k lo hi in
  let hyps = LQ_HYPS @ [ownp; hl; hh] in
  let th = List.fold_left MP (SPECL SPEC5 th) (map ASSUME hyps) in
  pk_hdom_local `c976od_family` m k lo hi hyps th (mk_list(map mk_numset al, `:num->bool`));;

